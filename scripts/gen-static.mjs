// Embeds public/* into src/static.ts so the Worker can serve the Mini App even without an ASSETS binding.
import fs from 'fs';
import path from 'path';
const dir = path.resolve('public');
const types = { '.html': 'text/html; charset=utf-8', '.js': 'application/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
const files = {};
for (const f of fs.readdirSync(dir).sort()) {
  const ext = path.extname(f);
  if (!types[ext]) continue;
  files['/' + f] = { type: types[ext], body: fs.readFileSync(path.join(dir, f), 'utf8') };
}
const out = '// AUTO-GENERATED by scripts/gen-static.mjs from public/. Do not edit.\n' +
  'export const STATIC_FILES: Record<string, { type: string; body: string }> = ' + JSON.stringify(files, null, 2) + ';\n';
fs.writeFileSync(path.resolve('src/static.ts'), out);
console.log('static files:', Object.keys(files).join(', '));
